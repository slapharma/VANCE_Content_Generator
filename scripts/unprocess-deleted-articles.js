// scripts/unprocess-deleted-articles.js
// For a named automation rule, removes 'processed' (consumedUrls / consumedTitles)
// entries for articles that were generated but are now deleted.
// Articles that were published to WordPress (wpPostId set) are left untouched.
//
// Usage:
//   vercel env pull .env.local
//   node --env-file=.env.local scripts/unprocess-deleted-articles.js [--dry-run]

import { kv } from '@vercel/kv';

const RULE_NAME = 'Blog Approved Titles_3rdJune2026';
const DRY = process.argv.includes('--dry-run');

async function main() {
  console.log(DRY ? 'DRY RUN — no changes will be saved' : 'LIVE — changes will be saved');
  console.log(`Looking for rule: "${RULE_NAME}"\n`);

  // 1. Find the rule by name
  const ruleIds = await kv.lrange('automation:rules:index', 0, -1);
  let rule = null;
  let ruleKey = null;
  for (const id of ruleIds) {
    const r = await kv.get(`automation:rule:${id}`);
    if (r && r.name === RULE_NAME) {
      rule = r;
      ruleKey = `automation:rule:${id}`;
      break;
    }
  }
  if (!rule) {
    console.error(`✗ Rule not found: "${RULE_NAME}"`);
    process.exit(1);
  }
  console.log(`✓ Found rule: ${rule.id} ("${rule.name}")`);

  // 2. Load all existing articles and find those generated by this rule
  const articleIds = await kv.lrange('content:index', 0, -1);
  console.log(`  Scanning ${articleIds.length} articles...\n`);

  // Build sets: sourceDocUrl / sourceDocName for WP-published articles from this rule
  const wpPublishedUrls = new Set();
  const wpPublishedTitles = new Set();

  for (const aid of articleIds) {
    const article = await kv.get(`content:${aid}`);
    if (!article) continue;
    if (article.automationRuleId !== rule.id) continue;
    if (article.wpPostId) {
      if (article.sourceDocUrl) wpPublishedUrls.add(article.sourceDocUrl);
      if (article.sourceDocName) {
        // consumedTitles stores the bare title; sourceDocName is "filename — title".
        // Strip the "filename — " prefix so we can match against consumedTitles.
        const sep = article.sourceDocName.indexOf(' — ');
        const bareTitle = sep >= 0 ? article.sourceDocName.slice(sep + 3) : article.sourceDocName;
        wpPublishedTitles.add(bareTitle);
      }
    }
  }

  console.log(`  WP-published source URLs  : ${wpPublishedUrls.size}`);
  console.log(`  WP-published source titles: ${wpPublishedTitles.size}`);
  if (wpPublishedUrls.size) {
    for (const u of wpPublishedUrls) console.log(`    URL (keep): ${u}`);
  }
  if (wpPublishedTitles.size) {
    for (const t of wpPublishedTitles) console.log(`    Title (keep): ${t}`);
  }
  console.log('');

  // 3. For each upload source, filter consumedUrls / consumedTitles
  let anyChange = false;
  const newSources = rule.sources.map((src) => {
    if (src.type !== 'upload') return src;

    const origUrls = Array.isArray(src.consumedUrls) ? src.consumedUrls : [];
    const origTitles = Array.isArray(src.consumedTitles) ? src.consumedTitles : [];

    const keptUrls = origUrls.filter((u) => wpPublishedUrls.has(u));
    const removedUrls = origUrls.filter((u) => !wpPublishedUrls.has(u));

    const keptTitles = origTitles.filter((t) => wpPublishedTitles.has(t));
    const removedTitles = origTitles.filter((t) => !wpPublishedTitles.has(t));

    if (removedUrls.length || removedTitles.length) {
      anyChange = true;
      console.log(`Source (upload):`);
      for (const u of removedUrls) console.log(`  ✗ Remove URL: ${u}`);
      for (const u of keptUrls) console.log(`  ✓ Keep URL  : ${u}`);
      for (const t of removedTitles) console.log(`  ✗ Remove title: ${t}`);
      for (const t of keptTitles) console.log(`  ✓ Keep title  : ${t}`);
    } else {
      console.log(`Source (upload): nothing to remove (${origUrls.length} URLs, ${origTitles.length} titles all WP-published)`);
    }

    return {
      ...src,
      consumedUrls: keptUrls,
      consumedTitles: keptTitles,
    };
  });

  // 4. Save
  if (!anyChange) {
    console.log('\nNo changes needed.');
    return;
  }

  console.log('');
  if (DRY) {
    console.log('DRY RUN — would save updated rule with filtered consumed arrays.');
  } else {
    await kv.set(ruleKey, {
      ...rule,
      sources: newSources,
      updatedAt: new Date().toISOString(),
    });
    console.log('✓ Rule saved. Deleted articles can now be reprocessed.');
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
