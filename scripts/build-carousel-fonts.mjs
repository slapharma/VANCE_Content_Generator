// scripts/build-carousel-fonts.mjs
//
// Regenerates lib/social/fonts/montserrat.js — the base64-inlined Montserrat
// faces the carousel renderer feeds to satori.
//
// Why inline base64 rather than .ttf files on disk: this project has no build
// step, and Vercel's bundler does not reliably trace runtime fs reads, so a
// .ttf sitting in the repo can go missing from the deployed function bundle. A
// plain `import` is always bundled and needs no vercel.json includeFiles entry.
//
// Usage:
//   1. Fetch the upstream statics (SIL OFL 1.1):
//        curl -sSLO https://github.com/JulietaUla/Montserrat/raw/master/fonts/ttf/Montserrat-Regular.ttf
//        curl -sSLO https://github.com/JulietaUla/Montserrat/raw/master/fonts/ttf/Montserrat-Bold.ttf
//   2. node scripts/build-carousel-fonts.mjs <dir-containing-the-ttfs>
//
// Step 2 subsets each face with pyftsubset (fontTools must be on PATH) from
// ~450 KB down to ~35 KB, then writes the module.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT  = join(REPO, 'lib', 'social', 'fonts', 'montserrat.js');

// Latin-1 plus exactly the punctuation the slide layouts use: en/em dash, curly
// quotes, arrows (→ ↑ ↓), bullet, middot, №, ≤, ≥, ™, €. Keep this in sync with
// the header comment written into the generated module.
const UNICODES = [
  'U+0000-00FF', 'U+0131', 'U+0152-0153', 'U+02BB-02BC', 'U+02C6', 'U+02DA',
  'U+02DC', 'U+0304', 'U+0308', 'U+0329', 'U+2000-206F', 'U+2074', 'U+20AC',
  'U+2116', 'U+2122', 'U+2190-2199', 'U+2212', 'U+2215', 'U+2264-2265',
  'U+FEFF', 'U+FFFD',
].join(',');

const FACES = [
  { file: 'Montserrat-Regular.ttf', constName: 'MONTSERRAT_REGULAR_B64', weight: 400 },
  { file: 'Montserrat-Bold.ttf',    constName: 'MONTSERRAT_BOLD_B64',    weight: 700 },
];

const srcDir = process.argv[2];
if (!srcDir) {
  console.error('Usage: node scripts/build-carousel-fonts.mjs <dir-containing-Montserrat-{Regular,Bold}.ttf>');
  process.exit(1);
}

// Wrap base64 at 120 chars so the generated module stays diff-friendly.
function wrapB64(b64) {
  const lines = [];
  for (let i = 0; i < b64.length; i += 120) lines.push(`  '${b64.slice(i, i + 120)}'`);
  return lines.join(' +\n');
}

const blocks = [];
for (const face of FACES) {
  const input  = join(srcDir, face.file);
  const output = join(srcDir, `sub-${face.file}`);
  execFileSync('pyftsubset', [
    input,
    `--output-file=${output}`,
    `--unicodes=${UNICODES}`,
    '--layout-features=kern,liga',
    '--no-hinting',
    '--desubroutinize',
  ], { stdio: 'inherit' });

  const b64 = readFileSync(output).toString('base64');
  console.log(`${face.file}: ${readFileSync(input).length} B → ${readFileSync(output).length} B subset (${b64.length} b64 chars)`);
  blocks.push({ ...face, b64 });
}

const header = `// lib/social/fonts/montserrat.js
//
// GENERATED by scripts/build-carousel-fonts.mjs — do not hand-edit.
//
// Montserrat (SIL Open Font License 1.1) — https://github.com/JulietaUla/Montserrat
// Two weights, Latin-subset via pyftsubset (~35 KB each) and base64-inlined so a
// plain import guarantees they land in the Vercel function bundle. Matches the
// app's own body font (index.html: 'Montserrat', sans-serif).
//
// satori outlines every glyph to <path>, so the rasteriser (resvg) never touches
// font data — these two buffers are the whole font story for the carousel
// pipeline. Subset covers Latin-1 plus the punctuation the slide layouts use:
// en/em dash, curly quotes, arrows (→ ↑ ↓), bullet, middot, №, ≤, ≥, ™, €.
//
// Regenerate: node scripts/build-carousel-fonts.mjs <dir-with-upstream-ttfs>
`;

const body = blocks
  .map((b) => `const ${b.constName} =\n${wrapB64(b.b64)};`)
  .join('\n\n');

const footer = `/**
 * Font descriptors in the shape satori expects. Decoded once at module load and
 * reused across every render. Both faces share the family name 'Montserrat', so
 * one \`fontFamily\` declaration plus \`fontWeight: 400 | 700\` picks the face.
 */
export const SATORI_FONTS = [
${blocks.map((b) => `  { name: 'Montserrat', data: Buffer.from(${b.constName}, 'base64'), weight: ${b.weight}, style: 'normal' },`).join('\n')}
];
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${header}\n${body}\n\n${footer}`);
console.log(`wrote ${OUT}`);
